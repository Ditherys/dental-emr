import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  readLinkedProjectId,
  validateRemoteDatabaseTestEnvironment,
} from "./remote-database-test-guard.mjs";

const repositoryRoot = fileURLToPath(new URL("..", import.meta.url));
const generatedTypesPath = join(
  repositoryRoot,
  "src",
  "types",
  "database.generated.ts",
);
const supabaseCliPath = join(
  repositoryRoot,
  "node_modules",
  "supabase",
  "dist",
  "supabase.js",
);
const checkOnly = process.argv.includes("--check");
const requireTestTarget = process.argv.includes("--require-test-target");
const projectId = process.env.SUPABASE_PROJECT_ID?.trim();
const testDatabaseUrl = process.env.SUPABASE_TEST_DB_URL?.trim();
const linkedProjectFile = join(
  repositoryRoot,
  "supabase",
  ".temp",
  "project-ref",
);

if (!existsSync(supabaseCliPath)) {
  console.error("Supabase CLI is not installed. Run `npm ci` first.");
  process.exit(1);
}

if (requireTestTarget) {
  if (!existsSync(linkedProjectFile)) {
    console.error(
      "No linked project was found. Link the explicitly designated Cloud TEST project first.",
    );
    process.exit(1);
  }

  try {
    validateRemoteDatabaseTestEnvironment(
      process.env,
      readLinkedProjectId(linkedProjectFile),
    );
  } catch (error) {
    console.error(
      `Database type check refused to continue: ${
        error instanceof Error ? error.message : "Unknown failure."
      }`,
    );
    process.exit(1);
  }
}

const projectArguments =
  requireTestTarget && testDatabaseUrl
    ? ["--db-url", testDatabaseUrl]
    : projectId
      ? ["--project-id", projectId]
      : ["--linked"];
const generated = execFileSync(
  process.execPath,
  [
    supabaseCliPath,
    "gen",
    "types",
    "typescript",
    ...projectArguments,
    "--schema",
    "public",
  ],
  {
    cwd: repositoryRoot,
    encoding: "utf8",
    maxBuffer: 10 * 1024 * 1024,
    stdio: ["ignore", "pipe", "inherit"],
  },
);

const normalizeLineEndings = (value) => value.replaceAll("\r\n", "\n");
const notice = [
  "// Generated by `npm run db:types` from the designated Supabase project.",
  "// Do not edit manually; update and apply a migration, then regenerate this file.",
  "",
  "",
].join("\n");
const expected = `${notice}${normalizeLineEndings(generated).trimEnd()}\n`;

if (checkOnly) {
  if (!existsSync(generatedTypesPath)) {
    console.error(
      "Generated database types are missing. Run `npm run db:types` and commit the result.",
    );
    process.exit(1);
  }

  const current = normalizeLineEndings(readFileSync(generatedTypesPath, "utf8"));

  if (current !== expected) {
    console.error(
      "Generated database types are stale. Run `npm run db:types` and commit the result.",
    );
    process.exit(1);
  }

  console.log("Generated database types are current.");
  process.exit(0);
}

mkdirSync(dirname(generatedTypesPath), { recursive: true });
writeFileSync(generatedTypesPath, expected, "utf8");
console.log("Updated src/types/database.generated.ts.");
