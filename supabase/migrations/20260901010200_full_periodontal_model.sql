  v_tooth_target text := $target$  insert into public.periodontal_tooth_measurements (
    organization_id, examination_id, tooth_fdi, mobility_miller, implant_context
  )
  select v_organization_id, v_new_id, m.tooth_fdi, m.mobility_miller, m.implant_context$target$;
  v_tooth_replacement text := $replacement$  insert into public.periodontal_tooth_measurements (
    organization_id, examination_id, tooth_fdi, mobility_miller, implant_context,
    tooth_present, notes, keratinized_gingiva_mm, gingival_thickness_mm,
    gingival_phenotype, miller_recession_class, cej_visible, root_concavity
  )
  select v_organization_id, v_new_id, m.tooth_fdi, m.mobility_miller, m.implant_context,
         m.tooth_present, m.notes, m.keratinized_gingiva_mm, m.gingival_thickness_mm,
         m.gingival_phenotype, m.miller_recession_class, m.cej_visible, m.root_concavity$replacement$;
  v_target text;
  v_replacement text;
begin
  -- Normalized for the same reason as the repair above: 20260828020400 is a
  -- CRLF file, so its stored body carries CR characters that no LF anchor
  -- written here would ever match. Re-creating from the normalized text also
  -- leaves one stable convention behind for the next forward migration.
  select pg_catalog.replace(
    pg_catalog.pg_get_functiondef('public.amend_periodontal_examination(uuid,uuid,uuid)'::regprocedure),
    pg_catalog.chr(13) || pg_catalog.chr(10),
    pg_catalog.chr(10)
