-- ---------------------------------------------------------------------------
-- 9. Surface index applicability against the authoritative implant context
-- ---------------------------------------------------------------------------

-- Enforced from BOTH sides. Checking only the surface row would leave the
-- inverse hole open: score a natural tooth, then flip the tooth to an implant,
-- and the examination is left carrying Silness-Loe scores on a peri-implant
-- sulcus with nothing to notice.
create function private.validate_perio_surface_index_context()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_implant boolean;
begin
  if tg_table_name = 'periodontal_tooth_measurements' then
    if new.implant_context then
      if exists (
        select 1
        from public.periodontal_plaque_measurements as surface
        where surface.organization_id = new.organization_id
          and surface.examination_id = new.examination_id
          and surface.tooth_fdi = new.tooth_fdi
          and (surface.plaque_index is not null or surface.gingival_index is not null)
      ) then
        raise check_violation using
          message = 'peri-implant surfaces use the modified plaque and bleeding indices';
      end if;
    else
      if exists (
        select 1
        from public.periodontal_plaque_measurements as surface
        where surface.organization_id = new.organization_id
          and surface.examination_id = new.examination_id
          and surface.tooth_fdi = new.tooth_fdi
          and (surface.modified_plaque_index is not null
               or surface.modified_bleeding_index is not null)
      ) then
        raise check_violation using
          message = 'modified plaque and bleeding indices apply only to peri-implant surfaces';
      end if;
    end if;

    return new;
  end if;

  select tooth.implant_context into v_implant
  from public.periodontal_tooth_measurements as tooth
  where tooth.organization_id = new.organization_id
    and tooth.examination_id = new.examination_id
    and tooth.tooth_fdi = new.tooth_fdi;

  if coalesce(v_implant, false) then
    if new.plaque_index is not null or new.gingival_index is not null then
      raise check_violation using
        message = 'peri-implant surfaces use the modified plaque and bleeding indices';
    end if;
  else
    if new.modified_plaque_index is not null or new.modified_bleeding_index is not null then
      raise check_violation using
        message = 'modified plaque and bleeding indices apply only to peri-implant surfaces';
    end if;
  end if;

  return new;
end
$$;

revoke all on function private.validate_perio_surface_index_context()
from public, anon, authenticated, service_role;

comment on function private.validate_perio_surface_index_context() is
  'Refuses the Silness-Loe / Loe-Silness index family on a peri-implant surface and the Mombelli modified family on a natural-tooth surface. It reads the implant context from the tooth row rather than trusting a duplicated flag on the surface row, and runs on both tables so neither writing order can leave a surface scored with the wrong family.';

create constraint trigger perio_plaque_surface_index_context_check
after insert or update on public.periodontal_plaque_measurements
deferrable initially immediate
for each row execute function private.validate_perio_surface_index_context();

create constraint trigger perio_tooth_surface_index_context_check
after insert or update on public.periodontal_tooth_measurements
deferrable initially immediate
for each row execute function private.validate_perio_surface_index_context();

-- ---------------------------------------------------------------------------
-- 10. The inferred-context merge must carry the new tooth properties
-- ---------------------------------------------------------------------------

-- private.enforce_periodontal_tooth_context creates a placeholder tooth row
-- when a site, surface, or furcation row arrives first, then merges the real
-- tooth row into it. That merge lists its columns explicitly, so without this
-- repair every property added above would be silently dropped whenever the
-- children happened to be written first. 20260828020520 is applied and is not
-- edited; the guarded-replace pattern verifies the target occurs exactly once
-- and fails closed with 55000.
do $migration$
declare
  v_definition text;
  v_repaired text;
  v_target text := $target$        update public.periodontal_tooth_measurements
        set tooth_present = new.tooth_present,
            mobility_miller = new.mobility_miller,
            implant_context = new.implant_context,
            context_inferred = false$target$;
  v_replacement text := $replacement$        update public.periodontal_tooth_measurements
        set tooth_present = new.tooth_present,
            mobility_miller = new.mobility_miller,
            implant_context = new.implant_context,
            notes = new.notes,
            keratinized_gingiva_mm = new.keratinized_gingiva_mm,
            gingival_thickness_mm = new.gingival_thickness_mm,
            gingival_phenotype = new.gingival_phenotype,
            miller_recession_class = new.miller_recession_class,
            cej_visible = new.cej_visible,
            root_concavity = new.root_concavity,
            context_inferred = false$replacement$;
begin
  -- The stored body carries whatever newline convention its source migration
  -- had on the machine that applied it, and THIS file is checked out with the
  -- convention of the machine replaying it. Both sides are normalized to LF so
  -- a multi-line anchor cannot silently fail on a CRLF checkout. Matching is
  -- exact substring counting, never a regex: an unescaped metacharacter in a
  -- SQL anchor would make the count meaningless.
  v_target := pg_catalog.replace(v_target, pg_catalog.chr(13) || pg_catalog.chr(10), pg_catalog.chr(10));
  v_replacement := pg_catalog.replace(v_replacement, pg_catalog.chr(13) || pg_catalog.chr(10), pg_catalog.chr(10));

  select pg_catalog.replace(
    pg_catalog.pg_get_functiondef('private.enforce_periodontal_tooth_context()'::regprocedure),
    pg_catalog.chr(13) || pg_catalog.chr(10),
    pg_catalog.chr(10)
  ) into v_definition;

  if (pg_catalog.length(v_definition)
      - pg_catalog.length(pg_catalog.replace(v_definition, v_target, '')))
     / pg_catalog.length(v_target) <> 1 then
    raise exception using errcode = '55000',
      message = 'enforce_periodontal_tooth_context inferred-merge update not found exactly once';
  end if;

  v_repaired := pg_catalog.replace(v_definition, v_target, v_replacement);

  if v_repaired = v_definition then
    raise exception using errcode = '55000',
      message = 'enforce_periodontal_tooth_context inferred-merge replacement made no change';
  end if;

  execute v_repaired;
end
$migration$;

-- ---------------------------------------------------------------------------
-- 11. An amendment clone must carry the expanded record
-- ---------------------------------------------------------------------------

-- public.amend_periodontal_examination clones the predecessor into the new
-- DRAFT with explicit column lists. Extending the tables without extending
-- those lists would make an amendment quietly discard every measurement added
-- above, which is exactly the silent overwrite the amendment path exists to
-- prevent. Three guarded replaces, each verified to occur exactly once.
--
-- The examination-level risk inputs are cloned because an amendment corrects
-- the same examination event and the patient's risk snapshot at that visit is
-- unchanged. The classification block is deliberately NOT cloned: a corrected
-- measurement set must be re-derived and re-confirmed, and the fingerprint of
-- the predecessor would not match the successor's measurements.
do $migration$
declare
  v_definition text;
  v_repaired text;
  v_step text;

  v_exam_target text := $target$    organization_id, patient_id, encounter_id, predecessor_examination_id,
    examination_kind, status, version, examined_at, examined_by, examined_provider_id
  ) values (
    v_organization_id, v_pred.patient_id, p_encounter_id, p_predecessor_examination_id,
    'AMENDMENT', 'DRAFT', v_pred.version + 1,
    pg_catalog.statement_timestamp(), v_actor_user_id, coalesce(v_provider_id, v_pred.examined_provider_id)
  )$target$;
  v_exam_replacement text := $replacement$    organization_id, patient_id, encounter_id, predecessor_examination_id,
    examination_kind, status, version, examined_at, examined_by, examined_provider_id,
    age_years_snapshot, smoking_status, cigarettes_per_day, diabetes_status,
    hba1c_percent, teeth_lost_to_periodontitis, radiographic_bone_loss_percent
  ) values (
    v_organization_id, v_pred.patient_id, p_encounter_id, p_predecessor_examination_id,
    'AMENDMENT', 'DRAFT', v_pred.version + 1,
    pg_catalog.statement_timestamp(), v_actor_user_id, coalesce(v_provider_id, v_pred.examined_provider_id),
    v_pred.age_years_snapshot, v_pred.smoking_status, v_pred.cigarettes_per_day, v_pred.diabetes_status,
    v_pred.hba1c_percent, v_pred.teeth_lost_to_periodontitis, v_pred.radiographic_bone_loss_percent
  )$replacement$;

  v_plaque_target text := $target$  insert into public.periodontal_plaque_measurements (
    organization_id, examination_id, tooth_fdi, surface, plaque_present
  )
  select v_organization_id, v_new_id, m.tooth_fdi, m.surface, m.plaque_present$target$;
  v_plaque_replacement text := $replacement$  insert into public.periodontal_plaque_measurements (
    organization_id, examination_id, tooth_fdi, surface, plaque_present,
    plaque_index, gingival_index, modified_plaque_index, modified_bleeding_index
