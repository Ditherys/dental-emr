-- Unified Clinical Chart workspace, task 9: the canonical periodontal and
-- peri-implant measurement model.
--
-- Forward-only. The five periodontal tables introduced by 20260828020200 and
-- refined by 20260828020515/020518/020520 are EXTENDED here. No parallel
-- canonical store is created, no applied migration is edited, and no clinical
-- measurement is invented: every new column is nullable with no default, so an
-- examination recorded before this migration stays exactly as readable as it
-- was, and a measurement that was never taken stays absent instead of
-- collapsing into zero or false.
--
-- Six changes:
--
-- 1. Unknown becomes representable. The gingival margin, bleeding on probing,
--    suppuration, and plaque presence carried NOT NULL DEFAULT 0/false, so a
--    site nobody assessed was indistinguishable from a healthy site. They lose
--    the NOT NULL and the default. Derived CAL is a generated column, so an
--    unknown gingival margin now yields an unknown CAL rather than silently
--    reporting the probing depth as the attachment level.
--
-- 2. Surface indices. The plaque table gains the Silness-Loe plaque index and
--    the Loe-Silness gingival index for natural teeth, and the Mombelli
--    modified plaque and modified bleeding indices for peri-implant surfaces.
--    Applicability is enforced, not documented: the natural-tooth family and
--    the peri-implant family may never appear on one surface, and a constraint
--    trigger refuses each family against the wrong context, reading the
--    authoritative implant flag from the tooth row rather than duplicating it.
--
-- 3. Tooth and implant properties. Keratinized gingiva width, gingival
--    thickness, and gingival phenotype apply to teeth and implants alike.
--    Miller recession class, CEJ visibility, and root concavity describe
--    structures an implant does not have and are refused in an implant
--    context. Miller mobility was already refused there.
--
-- 4. Examination risk inputs. Age snapshot, smoking status and cigarettes per
--    day, diabetes status and HbA1c, teeth lost to periodontitis, and
--    radiographic bone loss are the 2018 staging and grading inputs. Every one
--    is bounded; cigarettes per day is accepted only for a current smoker.
--
-- 5. Classification with provenance. The derived classification and the
--    clinician-confirmed classification are stored separately and never
--    overwrite one another. A confirmation must name its confirming user,
--    provider (tenant-safe), and time; a confirmation that departs from the
--    derived result must state a bounded, non-empty reason. Both
--    classifications carry a fingerprint over the canonical measurements, and a
--    constraint trigger refuses a fingerprint that is not the true digest, so
--    the provenance cannot be forged or back-dated.
--
-- 6. Amendment lineage. A superseding examination now records why. The reason
--    is bounded and non-empty, is accepted only with a predecessor, and is
--    MANDATORY once the amendment reaches FINAL — a DRAFT amendment may still
--    be autosaved without one, but the authoritative record that replaces
--    finalized clinical history can never exist unexplained. A partial unique
--    index refuses a second successor so the chain cannot fork.
--
-- FINAL immutability needs no new trigger: private.protect_finalized_perio_
-- examination and private.reject_finalized_perio_child_mutation reject the
-- whole row, carry no column list, and therefore already cover every column
-- added here. The suite proves that for the new columns rather than assuming
-- it.
--
-- This migration grants nothing. 20260901010201 owns the boundary assertion and
-- also grants nothing, because task 9 adds no browser-callable function.

